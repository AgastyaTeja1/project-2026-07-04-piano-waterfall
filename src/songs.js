/**
 * Preloaded songs as note event sequences.
 * Each note: { time (seconds), midi (0-127), duration (seconds), velocity (0-1), track (0-based) }
 */

/** Convert note name to MIDI number */
function n(name) {
  const notes = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };
  const match = name.match(/^([A-G])(#?)(\d)$/);
  if (!match) return 60;
  const [, letter, sharp, octave] = match;
  return notes[letter] + (sharp ? 1 : 0) + (parseInt(octave) + 1) * 12;
}

/** Build notes from a melody sequence: [[noteName, time, duration], ...] */
function melody(seq, trackIndex = 0, velocity = 0.75) {
  return seq.map(([note, time, dur]) => ({
    time,
    midi: n(note),
    duration: dur,
    velocity,
    track: trackIndex,
  }));
}

